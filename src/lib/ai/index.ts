/**
 * SolarAI - AI Service
 * ===============================================================
 * Modular AI layer with multiple provider support.
 *
 * CRITICAL: The AI NEVER performs critical calculations. We pass the
 * already-computed CalculationResults to it and ask only for
 * structured analysis, explanations, and recommendations.
 *
 * Provider selection (automatic):
 *   1. If GEMINI_API_KEY is set in .env → use Google Gemini
 *   2. Otherwise → try z-ai-web-dev-sdk (sandbox environment only)
 *   3. If both fail → use deterministic fallback (no AI needed)
 *
 * To get a free Gemini API key:
 *   1. Go to https://aistudio.google.com/apikey
 *   2. Create a key (free tier: 15 requests/min, 1500/day)
 *   3. Add to .env: GEMINI_API_KEY=your_key_here
 */

import type {
  AIRecommendation,
  CalculationResults,
  AssessmentInput,
  ChatMessage,
} from "@/types/solar";

// ---- Provider interface (swappable) ----
interface AIProvider {
  name: string;
  complete(messages: { role: string; content: string }[]): Promise<string>;
}

// ---- Provider 1: Google Gemini ----
class GeminiProvider implements AIProvider {
  name = "Google Gemini";
  private apiKey: string;
  private client: any = null;

  constructor(apiKey: string) {
    this.apiKey = apiKey;
  }

  private async init() {
    if (!this.client) {
      const { GoogleGenAI } = await import("@google/genai");
      this.client = new GoogleGenAI({ apiKey: this.apiKey });
    }
    return this.client;
  }

  async complete(
    messages: { role: string; content: string }[],
  ): Promise<string> {
    const ai = await this.init();

    // Gemini uses "user" and "model" roles. The first message (system prompt)
    // is handled via config, or we merge it into the first user message.
    // We'll convert: "assistant" role → "model", "system"/"assistant" → instructions
    let systemInstruction = "";
    const contents: Array<{ role: string; parts: Array<{ text: string }> }> =
      [];

    for (const msg of messages) {
      if (msg.role === "assistant" && messages.indexOf(msg) === 0) {
        // First assistant message acts as system prompt
        systemInstruction += msg.content + "\n";
      } else if (msg.role === "assistant" && messages.indexOf(msg) === 1) {
        // Second assistant message (assessment data) — also treat as system context
        systemInstruction += msg.content + "\n";
      } else if (msg.role === "user") {
        contents.push({ role: "user", parts: [{ text: msg.content }] });
      } else if (msg.role === "assistant") {
        contents.push({ role: "model", parts: [{ text: msg.content }] });
      }
    }

    const response = await ai.models.generateContent({
      model: "gemini-2.0-flash",
      contents,
      config: systemInstruction.trim()
        ? { systemInstruction: systemInstruction.trim() }
        : undefined,
    });

    return response.text || "";
  }
}

// ---- Provider 2: z-ai-web-dev-sdk (sandbox only) ----
class ZAIProvider implements AIProvider {
  name = "z-ai-web-dev-sdk (sandbox)";
  private client: any = null;

  private async init() {
    if (!this.client) {
      const ZAIModule = await import("z-ai-web-dev-sdk");
      const ZAI = ZAIModule.default;
      this.client = await ZAI.create();
    }
    return this.client;
  }

  async complete(
    messages: { role: string; content: string }[],
  ): Promise<string> {
    const zai = await this.init();
    const completion = await zai.chat.completions.create({
      messages: messages as any,
      thinking: { type: "disabled" },
    });
    return completion.choices[0]?.message?.content ?? "";
  }
}

// ---- Provider factory ----
function getProvider(): AIProvider | null {
  // 1. Try Gemini first (works everywhere with an API key)
  const geminiKey = process.env.GEMINI_API_KEY;
  if (geminiKey && geminiKey.trim().length > 0) {
    try {
      return new GeminiProvider(geminiKey.trim());
    } catch (e) {
      console.error("[AI] Failed to init Gemini provider:", e);
    }
  }

  // 2. Fall back to z-ai-web-dev-sdk (sandbox only)
  try {
    return new ZAIProvider();
  } catch (e) {
    console.error("[AI] Failed to init z-ai provider:", e);
  }

  return null;
}

// ---- System prompt ----
const SYSTEM_PROMPT = `You are SolarAI, an energy-analysis assistant. Use only the structured assessment data provided to you. Do not invent measurements, costs, energy production, government incentives, or technical specifications. Numerical results generated by the backend are authoritative. Explain results clearly and identify uncertainty. If information is insufficient, say what is missing. Do not present estimates as guarantees. Always remember the user's currency is the Indian Rupee (₹) unless told otherwise.`;

/**
 * Produce a structured AI recommendation from the calculation results.
 * Validates the response; falls back to a deterministic recommendation
 * if the AI returns invalid JSON or is unavailable.
 */
export async function analyzeAssessment(
  input: AssessmentInput,
  results: CalculationResults,
  weatherNote?: string,
): Promise<AIRecommendation> {
  const payload = {
    propertyType: input.propertyType,
    location: `${input.city}, ${input.state}, ${input.country}`,
    monthlyBill: input.monthlyBill,
    monthlyConsumptionKWh: results.monthlyConsumptionKWh,
    consumptionSource: results.consumptionSource,
    roof: {
      areaSqFt: input.roofArea,
      type: input.roofType,
      orientation: input.orientation,
      shading: input.shading,
    },
    solar: {
      sunlightHours: results.effectiveSunlightHours,
      panelType: input.panelType,
      budget: input.budget,
      energyOffsetPct: input.energyOffset,
    },
    results: {
      recommendedCapacityKW: results.recommendedCapacityKW,
      panelCount: results.panelCount,
      monthlyGenerationKWh: results.monthlyGenerationKWh,
      annualGenerationKWh: results.annualGenerationKWh,
      roofFeasibility: results.roofFeasibility,
      requiredRoofAreaSqFt: results.requiredRoofAreaSqFt,
      installationCostRange: `${results.installationCostMin}-${results.installationCostMax}`,
      monthlySavings: results.monthlySavings,
      annualSavings: results.annualSavings,
      paybackYears: results.paybackYears,
      annualCO2ReductionTons: results.annualCO2ReductionTons,
      suitabilityScore: results.suitabilityScore,
      factors: results.factors,
      batteryRecommendation: results.batteryRecommendation,
    },
    weatherNote: weatherNote ?? "not provided",
  };

  const userPrompt = `Analyze this solar assessment and return ONLY valid JSON (no markdown fences, no extra text) with exactly these keys:
{
  "summary": "string - 1-2 sentence overall assessment",
  "recommendedSystem": "string - e.g. '5 kW'",
  "keyReasons": ["string", ...] - 3-5 reasons supporting suitability,
  "recommendations": ["string", ...] - 3-5 actionable next steps,
  "warnings": ["string", ...] - 1-3 caveats/uncertainties,
  "efficiencyTips": ["string", ...] - 3-5 efficiency improvement tips
}

Use ONLY the numbers given below. Do not recalculate. Be specific and practical.

ASSESSMENT_DATA:
${JSON.stringify(payload, null, 2)}`;

  const provider = getProvider();

  // No provider available → use fallback immediately
  if (!provider) {
    console.warn(
      "[AI] No AI provider available. Using deterministic fallback.",
    );
    return fallbackRecommendation(results);
  }

  try {
    const messages = [
      { role: "assistant", content: SYSTEM_PROMPT },
      { role: "user", content: userPrompt },
    ];
    const raw = await provider.complete(messages);
    const parsed = parseAIRecommendation(raw);
    if (parsed) return parsed;
    console.warn(
      "[AI] Invalid response, using fallback. Raw:",
      raw.slice(0, 200),
    );
    return fallbackRecommendation(results);
  } catch (err) {
    console.error(`[AI] analyzeAssessment error (${provider.name}):`, err);
    return fallbackRecommendation(results);
  }
}

function parseAIRecommendation(raw: string): AIRecommendation | null {
  if (!raw) return null;
  let text = raw.trim();
  // strip code fences if present
  text = text
    .replace(/^```(?:json)?/i, "")
    .replace(/```$/i, "")
    .trim();
  // try to extract the first {...} block
  const start = text.indexOf("{");
  const end = text.lastIndexOf("}");
  if (start >= 0 && end > start) text = text.slice(start, end + 1);
  try {
    const obj = JSON.parse(text);
    if (typeof obj.summary !== "string") return null;
    const arr = (v: any) =>
      Array.isArray(v)
        ? v.filter((x) => typeof x === "string").slice(0, 8)
        : [];
    return {
      summary: String(obj.summary).slice(0, 600),
      recommendedSystem: String(obj.recommendedSystem || "").slice(0, 80),
      keyReasons: arr(obj.keyReasons),
      recommendations: arr(obj.recommendations),
      warnings: arr(obj.warnings),
      efficiencyTips: arr(obj.efficiencyTips),
    };
  } catch {
    return null;
  }
}

function fallbackRecommendation(results: CalculationResults): AIRecommendation {
  return {
    summary:
      results.suitabilityScore >= 70
        ? `Your property shows ${results.suitabilityLabel.toLowerCase()} for a ${results.recommendedCapacityKW} kW solar system.`
        : `Your property has ${results.suitabilityLabel.toLowerCase()}. A ${results.recommendedCapacityKW} kW system is technically possible but review the factors below.`,
    recommendedSystem: `${results.recommendedCapacityKW} kW`,
    keyReasons: [
      results.roofFeasibility === "Sufficient"
        ? "Available roof area is sufficient for the recommended system"
        : "Roof area is a constraint — consider a smaller system or higher-efficiency panels",
      `Estimated ${results.monthlyGenerationKWh} kWh/month generation`,
      `Payback in ~${results.paybackYears} years`,
      `Annual CO₂ reduction of ${results.annualCO2ReductionTons} tons`,
    ],
    recommendations: [
      results.roofFeasibility !== "Sufficient"
        ? "Consider high-efficiency monocrystalline panels to maximize output per sq ft"
        : "Proceed with a site survey by a certified installer",
      "Obtain 2-3 quotes from MNRE-registered installers",
      "Verify net-metering availability with your DISCOM",
      results.batteryRecommendation.status !== "Not needed"
        ? `Consider a ${results.batteryRecommendation.suggestedCapacityKWh} kWh battery for ${results.batteryRecommendation.primaryBenefit.toLowerCase()}`
        : "A battery is optional at current consumption patterns",
    ],
    warnings: [
      "Actual generation varies with weather, shading and panel orientation",
      "Costs and savings are estimates — confirm with installer quotes",
      "Subsidy and net-metering policies vary by state",
    ],
    efficiencyTips: [
      "Schedule heavy loads (washing machine, pump) during solar-production hours",
      "Use energy-efficient appliances to reduce overall consumption",
      "Keep panels clean to maintain rated output",
      "Monitor generation regularly to detect underperformance early",
    ],
  };
}

/**
 * Conversational AI advisor. Answers use the user's ACTUAL assessment data
 * (passed in as context) so the model cannot invent user measurements.
 */
export async function chatAboutAssessment(
  question: string,
  history: ChatMessage[],
  input: AssessmentInput,
  results: CalculationResults,
  aiRec: AIRecommendation | null,
): Promise<string> {
  const context = {
    propertyType: input.propertyType,
    location: `${input.city}, ${input.state}, ${input.country}`,
    monthlyBill: input.monthlyBill,
    monthlyConsumptionKWh: results.monthlyConsumptionKWh,
    roof: {
      areaSqFt: input.roofArea,
      type: input.roofType,
      orientation: input.orientation,
      shading: input.shading,
    },
    solar: {
      sunlightHours: results.effectiveSunlightHours,
      panelType: input.panelType,
      budget: input.budget,
      energyOffsetPct: input.energyOffset,
    },
    results: {
      recommendedCapacityKW: results.recommendedCapacityKW,
      panelCount: results.panelCount,
      monthlyGenerationKWh: results.monthlyGenerationKWh,
      annualGenerationKWh: results.annualGenerationKWh,
      roofFeasibility: results.roofFeasibility,
      installationCostAvg: results.installationCostAvg,
      monthlySavings: results.monthlySavings,
      annualSavings: results.annualSavings,
      lifetimeSavings: results.lifetimeSavings,
      paybackYears: results.paybackYears,
      annualCO2ReductionTons: results.annualCO2ReductionTons,
      suitabilityScore: results.suitabilityScore,
      factors: results.factors,
      batteryRecommendation: results.batteryRecommendation,
    },
    aiRecommendation: aiRec,
  };

  const messages: { role: string; content: string }[] = [
    { role: "assistant", content: SYSTEM_PROMPT },
    {
      role: "assistant",
      content:
        "Here is the user's authoritative assessment data. Answer ONLY using this data. Do not invent numbers. If the user asks about something not in the data, say so. Keep answers concise (2-4 sentences) and practical.\n\nASSESSMENT_DATA:\n" +
        JSON.stringify(context, null, 2),
    },
  ];

  // include recent history (last 8 messages) for context
  for (const m of history.slice(-8)) {
    messages.push({ role: m.role, content: m.content });
  }
  messages.push({ role: "user", content: question });

  const provider = getProvider();

  // No provider available → return a helpful deterministic response
  if (!provider) {
    console.warn(
      "[AI] No AI provider available for chat. Using deterministic response.",
    );
    return deterministicChatResponse(question, results, aiRec);
  }

  try {
    const reply = await provider.complete(messages);
    return (
      reply || "I'm sorry, I couldn't generate a response. Please try again."
    );
  } catch (err) {
    console.error(`[AI] chat error (${provider.name}):`, err);
    return deterministicChatResponse(question, results, aiRec);
  }
}

/**
 * Deterministic fallback for chat when no AI provider is available.
 * Answers common questions using the actual assessment data.
 */
function deterministicChatResponse(
  question: string,
  results: CalculationResults,
  aiRec: AIRecommendation | null,
): string {
  const q = question.toLowerCase();
  const r = results;

  if (q.includes("panel") || q.includes("how many")) {
    return `Based on your assessment, you need ${r.panelCount} panels of ${r.panelWattage}W each for your ${r.recommendedCapacityKW} kW system. This requires approximately ${r.requiredRoofAreaSqFt} sq ft of roof space, and your roof feasibility is ${r.roofFeasibility}.`;
  }

  if (q.includes("save") || q.includes("saving") || q.includes("money")) {
    return `Your estimated monthly savings are ₹${r.monthlySavings.toLocaleString("en-IN")} and annual savings of ₹${r.annualSavings.toLocaleString("en-IN")}. Over the ${25}-year lifetime of the system, you could save approximately ₹${r.lifetimeSavings.toLocaleString("en-IN")} (accounting for tariff escalation and panel degradation).`;
  }

  if (q.includes("battery")) {
    const b = r.batteryRecommendation;
    return `Battery recommendation: ${b.status}. Suggested capacity: ${b.suggestedCapacityKWh} kWh. Primary benefit: ${b.primaryBenefit}. ${b.rationale}`;
  }

  if (q.includes("suitable") || q.includes("why")) {
    return `Your property has a suitability score of ${r.suitabilityScore}/100 (${r.suitabilityLabel}). Key factors: Roof suitability ${Math.round(r.factors.roofSuitability * 100)}%, Solar resource ${Math.round(r.factors.solarResource * 100)}%, Budget suitability ${Math.round(r.factors.budgetSuitability * 100)}%, Energy demand ${Math.round(r.factors.energyDemand * 100)}%, Shading ${Math.round(r.factors.shading * 100)}%.`;
  }

  if (q.includes("payback") || q.includes("return")) {
    return `Your estimated payback period is ${r.paybackYears} years. This means the system pays for itself through electricity savings in about ${r.paybackYears} years, after which you continue to save for the remaining ${25 - r.paybackYears} years of the system's lifetime.`;
  }

  if (q.includes("co2") || q.includes("carbon") || q.includes("environment")) {
    return `Your solar system would reduce CO₂ emissions by approximately ${r.annualCO2ReductionTons} tons per year and ${r.lifetimeCO2ReductionTons} tons over its 25-year lifetime. This is equivalent to taking about ${Math.round(r.annualCO2ReductionTons / 4.6)} cars off the road each year.`;
  }

  if (q.includes("efficiency") || q.includes("improve")) {
    return `To improve your solar efficiency: 1) Schedule heavy loads (washing machine, water pump) during solar-production hours (10am-4pm). 2) Use energy-efficient appliances to reduce overall consumption. 3) Keep panels clean to maintain rated output. 4) Monitor generation regularly to detect underperformance early.`;
  }

  if (
    q.includes("consumption") ||
    q.includes("increase") ||
    q.includes("usage")
  ) {
    return `Your current monthly consumption is ${r.monthlyConsumptionKWh} kWh. If your consumption increases, your solar system will offset a smaller percentage of your total usage, increasing grid dependency. You can use the What-If Simulator to test different consumption scenarios and see how they affect savings and payback.`;
  }

  // Default response
  return `I can help with questions about your solar assessment. Your system: ${r.recommendedCapacityKW} kW, generating ${r.monthlyGenerationKWh} kWh/month, with ${r.paybackYears} years payback and suitability score ${r.suitabilityScore}/100. Try asking about panels, savings, battery, payback, CO₂ reduction, or efficiency tips. (Note: AI provider not configured — set GEMINI_API_KEY in .env for full AI responses.)`;
}
